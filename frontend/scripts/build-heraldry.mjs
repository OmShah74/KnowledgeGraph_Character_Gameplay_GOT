// Extracts the heraldic glyphs used by the app from game-icons.net (CC BY 3.0, via @iconify-json/game-icons)
// into a small TypeScript module so no icon data is fetched at runtime.
import { createRequire } from "module";
import { writeFileSync } from "fs";
const require = createRequire(import.meta.url);
const set = require("@iconify-json/game-icons/icons.json");
const NAMES = [
  "wolf-head", "lion", "stag-head", "dragon-head", "octopus", "rose", "sun-spear", "fish-escape", "eagle-head", "crowned-skull",
  "tower-bridge", "hunting-horn", "bear-head", "giant", "heraldic-sun", "hound", "galleon", "sun", "hummingbird", "lizardman",
  "two-coins", "lightning-arc", "gauntlet", "rune-stone", "broadsword", "falling-star", "raven", "pine-tree", "black-knight-helm",
  "crown", "seven-pointed-star", "lightning-tree", "hooded-figure", "spears", "horse-head", "crossed-swords", "coins", "open-book",
  "sand-snake", "frozen-orb", "deku-tree", "harpy", "crown-coin", "stone-throne", "dragon-spiral", "flame", "snowflake-1",
  "scroll-unfurled", "wax-seal", "castle", "skull-crossed-bones", "all-seeing-eye", "drama-masks", "hourglass", "treasure-map",
  "candle-flame", "quill-ink", "envelope", "throne-king", "heart-tower", "hand", "brain", "mounted-knight", "compass",
];
const out = {};
for (const n of NAMES) {
  const ic = set.icons[n];
  if (!ic) throw new Error(`missing icon ${n}`);
  out[n] = { body: ic.body, w: ic.width || set.width || 512, h: ic.height || set.height || 512 };
}
const ts = `// AUTO-GENERATED by scripts/build-heraldry.mjs — do not edit.\n// Icons: game-icons.net (CC BY 3.0) by Lorc, Delapouite & contributors.\n` +
  `export const HERALDRY: Record<string, { body: string; w: number; h: number }> = ${JSON.stringify(out, null, 0)};\n`;
writeFileSync(new URL("../src/lib/heraldry-icons.ts", import.meta.url), ts);
console.log(`wrote ${Object.keys(out).length} icons`);
